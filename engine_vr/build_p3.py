def read_engine(name):
    return (ENGINE / name).read_text(encoding="utf-8")


def segment(name, start, end):
    lines = read_engine(name).splitlines(keepends=True)
    if not (1 <= start <= end <= len(lines)):
        raise SystemExit(f"{name}: bad range {start}-{end} of {len(lines)}")
    return "".join(lines[start - 1:end])


def apply_subs(text, subs, label):
    for old, new, count in subs:
        got = text.count(old)
        if got != count:
            raise SystemExit(f"{label}: substitution {old!r} occurred {got} "
                             f"time(s), declared {count}")
        text = text.replace(old, new)
    return text


def build_body(target, blocks):
    out = ["\n",
           "# -----------------------------------------------------------------"
           "---------------\n",
           "# Copied from the moderngl build by engine_vr/build_p3.py: verbatim\n",
           "# except the substitutions named in each block header; no constant,\n",
           "# threshold or ordering was retyped. Per-line noqa comments may be\n",
           "# added by build_p3.py for ruff (ast-dump verified, comments only).\n",
           "# -----------------------------------------------------------------"
           "---------------\n",
           "\n"]
    for name, s, e, subs in blocks:
        seg = apply_subs(segment(name, s, e), subs, f"{target}:{name} {s}-{e}")
        tag = (" + ".join(repr(o.strip()) for o, _n, _c in subs) if subs
               else "verbatim")
        out.append(f"# ---- copied from engine/{name}:{s}-{e} ({tag})\n")
        out.append(seg.rstrip("\n") + "\n\n\n")
    return "".join(out).rstrip("\n") + "\n"


def splice(target, body, path=None):
    path = Path(path) if path is not None else HERE / target
    text = path.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{target}: copy markers not found")
    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    new = head + BEGIN + "\n" + body + "\n" + END + tail
    path.write_text(new, encoding="utf-8")
    return path, new


def region_rows(text):
    """(first, last) physical rows of the generated region."""
    lines = text.split("\n")
    a = lines.index(BEGIN) + 2          # first line after BEGIN
    b = lines.index(END)                # line before END (1-based inclusive)
    return a, b


def ruff_violations(path):
    p = subprocess.run([sys.executable, "-m", "ruff", "check", "--select",
                        "E,F", "--output-format=json", str(path)],
                       cwd=ROOT, capture_output=True, text=True)
    if not p.stdout.strip():
        return []
    try:
        return json.loads(p.stdout)
    except json.JSONDecodeError:
        raise SystemExit(f"ruff output not json: {p.stdout[:200]}"
                         f"{p.stderr[:200]}")


def multiline_string_rows(path):
    """Rows covered by multi-line string tokens (annotating them = drift)."""
    import tokenize
    rows = set()
    with tokenize.open(str(path)) as fh:
        for tok in tokenize.generate_tokens(fh.readline):
            if tok.type == tokenize.STRING and tok.end[0] > tok.start[0]:
                rows.update(range(tok.start[0], tok.end[0] + 1))
    return rows


def _norm_dump(tree):
    """ast.dump with every docstring whitespace-normalised (rewrap-proof)."""
    t = ast.parse(ast.unparse(tree)) if False else tree
    for node in ast.walk(t):
        body = getattr(node, "body", None)
        if not isinstance(body, list) or not body:
            continue
        first = body[0]
        if (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)):
            first.value.value = " ".join(first.value.value.split())
    return ast.dump(t)


def wrap_prose(value, width):
    """Greedy word wrap that keeps paragraph and bullet breaks."""
    out = []
    for para in value.split("\n"):
        words = para.split()
        if not words:
            out.append("")
            continue
        line = words[0]
        for w in words[1:]:
            if len(line) + 1 + len(w) > width:
                out.append(line)
                line = w
            else:
                line += " " + w
        out.append(line)
    text = "\n".join(out)
    if value.startswith(" ") and not text.startswith(" "):
        text = " " + text
    if value.endswith(" ") and not text.endswith(" "):
        text += " "
    return text


def rewrap_docstrings(path, lo, hi, report):
    """Re-wrap over-long docstrings inside the copied region, prose only.

    The engine's docstrings predate the 88-column default and ruff has no way
    to suppress a violation inside a string literal, so a long docstring is
    re-wrapped instead of annotated. That changes only whitespace INSIDE a
    docstring: after rewriting, the tree is re-parsed and compared with the
    pre-rewrite dump with all docstrings whitespace-normalised, and any module
    that does not match is restored byte-for-byte.
    """
    import re
    src = path.read_text(encoding="utf-8")
    try:
        base_tree = ast.parse(src)
    except SyntaxError:
        return
    base_dump = _norm_dump(ast.parse(ast.unparse(base_tree)) if False else
                           ast.parse(src))
    lines = src.split("\n")
    targets = []
    for node in ast.walk(base_tree):
        body = getattr(node, "body", None)
        if not isinstance(body, list) or not body:
            continue
        first = body[0]
        if not (isinstance(first, ast.Expr)
                and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)):
            continue
        c = first.value
        if not (lo <= c.lineno and c.end_lineno <= hi):
            continue
        rows = range(c.lineno - 1, c.end_lineno)
        if any(len(lines[i]) > 88 for i in rows):
            targets.append(c)
    if not targets:
        return
    for c in sorted(targets, key=lambda c: -c.lineno):
        first_line = lines[c.lineno - 1]
        indent = first_line[:len(first_line) - len(first_line.lstrip())]
        raw = "\n".join(lines[c.lineno - 1:c.end_lineno])
        m = re.match(r'^\s*("""|\'\'\')', raw)
        if not m or re.match(r'^\s*[a-zA-Z]+("""|\'\'\')', raw):
            report.append(f"{path.name}:{c.lineno}: docstring prefix/quote "
                          f"shape not re-wrappable - left as is")
            continue
        quote = m.group(1)
        wrapped = wrap_prose(c.value, 85 - len(indent))
        body = quote + wrapped + quote
        seg = [(indent + s).rstrip() for s in body.split("\n")]
        lines[c.lineno - 1:c.end_lineno] = seg
    candidate = "\n".join(lines)
    try:
        same = _norm_dump(ast.parse(candidate)) == base_dump
    except SyntaxError:
        same = False
    if not same:
        report.append(f"{path.name}: docstring re-wrap REJECTED (tree differs)"
                      f" - module restored")
        return
    path.write_text(candidate, encoding="utf-8")


def annotate(path, lo, hi, report):
    """Append a per-line noqa comment to violations inside the copied region.

    Applied one line at a time: if an annotation would change the parse tree
    (a comment after a backslash continuation, or inside a multi-line string),
    it is dropped and reported instead of applied, so a copied block can never
    silently stop being the code the engine runs.
    """
    for _attempt in range(300):
        before = path.read_text(encoding="utf-8")
        try:
            base_dump = ast.dump(ast.parse(before))
        except SyntaxError as exc:
            raise SystemExit(f"{path.name}: generated text does not parse: "
                             f"{exc}")
        hits = [v for v in ruff_violations(path)
                if v.get("filename", "").endswith(path.name)
                and lo <= v["location"]["row"] <= hi]
        if not hits:
            return
        unsafe = multiline_string_rows(path)
        pragma_re = re.compile(r"(?:^|(?<=\s))#\s*noqa"
                               r"(?::\s*([A-Za-z0-9,\s]+))?")
        lines = before.split("\n")
        skipped = 0
        for v in sorted(hits, key=lambda v: v["location"]["row"]):
            row = v["location"]["row"]
            code = v.get("code") or "E501"
            line = lines[row - 1]
            pragma = pragma_re.search(line)
            if pragma is not None:
                # extend an existing pragma - a second "# noqa" inside the same
                # comment is not a pragma and ruff silently ignores it
                if pragma.group(1) is None:
                    skipped += 1        # bare noqa already covers the rule
                    continue
                codes = [c for c in re.split(r"[,\s]+",
                                             pragma.group(1).strip()) if c]
                if code in codes:
                    report.append(f"{path.name}:{row}: {code} still reported "
                                  f"under pragma {codes} - left alone")
                    skipped += 1
                    continue
                codes.append(code)
                newline = (line[:pragma.start()] + "# noqa: "
                           + ",".join(codes))
            elif row in unsafe:
                report.append(f"{path.name}:{row}: {code} inside a multi-line "
                              f"string - NOT annotated")
                skipped += 1
                continue
            elif line.rstrip().endswith("\\"):
                report.append(f"{path.name}:{row}: {code} on a backslash "
                              f"continuation - NOT annotated")
                skipped += 1
                continue
            else:
                newline = line + f"  # noqa: {code}"
            lines[row - 1] = newline
            try:
                keeps = ast.dump(ast.parse("\n".join(lines))) == base_dump
            except SyntaxError:
                keeps = False
            if not keeps:
                lines[row - 1] = line
                report.append(f"{path.name}:{row}: {code} - NOT annotated "
                              f"(annotation changed the parse tree)")
                skipped += 1
                continue
            base_dump = ast.dump(ast.parse("\n".join(lines)))
        candidate = "\n".join(lines)
        if candidate == before:
            report.append(f"{path.name}: {skipped} violation(s) left "
                          f"unannotatable")
            return
        path.write_text(candidate, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="report what would change, write nothing")
    args = ap.parse_args()
    report = []
    for target, blocks in COPIES.items():
        body = build_body(target, blocks)
        copied = sum(e - s + 1 for _n, s, e, _b in blocks)
        if args.check:
            # N2 (review_p3): --check used to splice the file first and only
            # then raise. Run the FULL pipeline on a scratch copy and diff
            # it instead - the real file is never written in this mode (and
            # the trailing ruff pass is read-only).
            import difflib
            import tempfile
            path = HERE / target
            text = path.read_text(encoding="utf-8")
            with tempfile.TemporaryDirectory(prefix="p3check_") as td:
                scratch = Path(td) / target
                scratch.write_text(text, encoding="utf-8")
                scratch, new = splice(target, body, path=scratch)
                lo, hi = region_rows(new)
                rewrap_docstrings(scratch, lo, hi, report)
                lo, hi = region_rows(scratch.read_text(encoding="utf-8"))
                annotate(scratch, lo, hi, report)
                after = scratch.read_text(encoding="utf-8")
            delta = list(difflib.unified_diff(text.splitlines(),
                                              after.splitlines(),
                                              lineterm="", n=0))
            ndiff = max(len(delta) - 2, 0)
            state = "up to date" if not ndiff else f"WOULD CHANGE ({ndiff} diff lines)"
            print(f"{target}: {state}, {len(after.splitlines())} lines "
                  f"total, {copied} copied engine lines, region {lo}-{hi}")
            continue
        path, new = splice(target, body)
        lo, hi = region_rows(new)
        rewrap_docstrings(path, lo, hi, report)
        lo, hi = region_rows(path.read_text(encoding="utf-8"))
        annotate(path, lo, hi, report)
        n = len(new.splitlines())
        print(f"{target}: {n} lines total, {copied} copied engine lines, "
              f"region {lo}-{hi}")
    for line in report:
        print("NOTE " + line)
    leftover = []
    for target in COPIES:
        for v in ruff_violations(HERE / target):
            leftover.append(f"{target}:{v['location']['row']}: "
                            f"{v.get('code')} {v.get('message', '')[:60]}")
    if leftover:
        print("RESIDUAL ruff violations (not auto-annotated):")
        for line in leftover[:40]:
            print("  " + line)
    else:
        print("ruff E,F clean on all three drivers")


if __name__ == "__main__":
    main()