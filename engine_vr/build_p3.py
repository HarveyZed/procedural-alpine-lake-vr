"""build_p3.py - assemble the P3 drivers from the engine originals.

The Phase-3 brief forbids algorithm or constant drift, so the numpy stages and
the drivers of engine/bake.py, engine/erosion.py and engine/features.py are not
retyped: they are extracted from the originals by line range and spliced into
the marker-delivered region at the end of each VR driver.

What this script guarantees, and what it prints:

  * every block carries a "copied from engine/<file>:<start>-<end>" header;
  * every textual edit (import substitutions, program-name disambiguation) is
    declared as an (old, new, expected_count) triple and asserted - an edit
    that occurs fewer or more times than declared aborts the build;
  * after mechanical "# noqa: <rule>" annotation (the engine predates ruff's
    default 88-column limit), the whole module is re-parsed and compared with
    ast.dump() against the pre-annotation text, so annotation can only ever
    have added comments. Any annotation that would change the AST is reverted
    and reported instead of applied.

Run:  .venv/bin/python engine_vr/build_p3.py [--check]
"""

